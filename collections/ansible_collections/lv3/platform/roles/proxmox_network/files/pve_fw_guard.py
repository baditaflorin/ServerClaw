#!/usr/bin/env python3
"""Compare, back up and install the rendered per-VM Proxmox firewall files without deleting live rules.

The proxmox_network role renders every guest's policy to a staging file (/root/.lv3-vm-<vmid>.fw) and used to copy it over
/etc/pve/firewall/<vmid>.fw. The live files have other writers than the render: hand-authored rules, a set migrated from
the guest, and on some VMs a `# BEGIN <label>` ... `# END <label>` block generated by another tool. The copy deleted
all of them, and the check-mode diff compared the render with the staging copy, so a destructive change looked additive.
This script is the one place that decides what may be written:

  plan   read only; prints, per VM, the diff of the live file against the render and what the install would remove.
  apply  does the same, then, only if nothing would be removed (or removal is explicitly allowed), copies every file it is
         about to change to <backup-root>/fw-backup-<timestamp>/ with a restore.sh, and installs the render.

A removal is any rule or option line, in any section, that the live file has and the render does not, and any managed
block the render does not carry. Added lines, comment-only differences, whitespace, order and a trailing `# comment` on a
rule are not removals. Either mode exits 2 when a removal is refused, and apply then writes nothing at all, not even a
backup. Both modes take the same flags so that the check-mode answer is the real run's answer.

Exit status: 0 = nothing to remove (or removal allowed), 1 = error, 2 = removal refused.
Standard library only; the Proxmox host's Python 3.11 is enough.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import shlex
import shutil
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

EXIT_OK = 0
EXIT_ERROR = 1
EXIT_REFUSED = 2

SECTION_RE = re.compile(r"^\[(?P<name>[^\]]*)\]")
BLOCK_BEGIN_RE = re.compile(r"^#\s*BEGIN\s+(?P<label>\S.*?)\s*$")
BLOCK_END_RE = re.compile(r"^#\s*END\s+(?P<label>\S.*?)\s*$")
TRAILING_COMMENT_RE = re.compile(r"\s+#.*$")

ALLOW_VARIABLE = "proxmox_network_allow_rule_removal"


@dataclass(frozen=True)
class FirewallLine:
    """One rule, option, alias or ipset entry (anything that is not blank or a comment)."""

    section: str
    key: str  # whitespace collapsed and without a trailing comment: what two files are compared on
    text: str  # as written, stripped
    block: str  # label of the enclosing managed block, "" outside one


@dataclass
class ParsedFile:
    lines: list[FirewallLine] = field(default_factory=list)
    blocks: list[str] = field(default_factory=list)  # managed block labels in file order
    comments: list[str] = field(default_factory=list)  # comment lines that are not block markers

    def keys(self) -> set[tuple[str, str]]:
        return {(line.section, line.key) for line in self.lines}


@dataclass
class VmPlan:
    vmid: int
    live_path: Path
    staged_path: Path
    state: str  # unchanged | new | additive | removes
    added: list[FirewallLine]
    removed: list[FirewallLine]
    removed_blocks: list[str]
    dropped_comments: int
    diff: list[str]
    render_text: str
    live_text: str | None

    @property
    def removes(self) -> bool:
        return bool(self.removed or self.removed_blocks)

    @property
    def changed(self) -> bool:
        return self.state != "unchanged"


def _section_key(name: str) -> str:
    head, _, rest = " ".join(name.split()).partition(" ")
    return head.upper() + (" " + rest if rest else "")


def parse_firewall_file(text: str) -> ParsedFile:
    parsed = ParsedFile()
    section = ""
    open_blocks: list[str] = []
    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped:
            continue
        begin = BLOCK_BEGIN_RE.match(stripped)
        if begin:
            open_blocks.append(begin.group("label"))
            parsed.blocks.append(begin.group("label"))
            continue
        end = BLOCK_END_RE.match(stripped)
        if end:
            if end.group("label") in open_blocks:
                while open_blocks and open_blocks.pop() != end.group("label"):
                    pass
            continue
        if stripped.startswith("#"):
            parsed.comments.append(" ".join(stripped.split()))
            continue
        header = SECTION_RE.match(stripped)
        if header:
            section = _section_key(header.group("name"))
            continue
        key = " ".join(TRAILING_COMMENT_RE.sub("", stripped).split())
        parsed.lines.append(
            FirewallLine(section=section, key=key, text=stripped, block=open_blocks[-1] if open_blocks else "")
        )
    return parsed


def plan_vm(vmid: int, live_dir: Path, stage_dir: Path) -> VmPlan:
    live_path = live_dir / f"{vmid}.fw"
    staged_path = stage_dir / f".lv3-vm-{vmid}.fw"
    if not staged_path.is_file():
        raise FileNotFoundError(f"the render for VM {vmid} is missing: {staged_path}")
    render_text = staged_path.read_text(encoding="utf-8")
    render = parse_firewall_file(render_text)
    if not render.lines:
        raise ValueError(
            f"the render for VM {vmid} has no rule or option line; refusing to treat it as the desired state"
        )

    live_text = live_path.read_text(encoding="utf-8") if live_path.is_file() else None
    live = parse_firewall_file(live_text or "")
    render_keys = render.keys()
    live_keys = live.keys()
    added = [line for line in render.lines if (line.section, line.key) not in live_keys]
    removed = [line for line in live.lines if (line.section, line.key) not in render_keys]
    removed_blocks = [label for label in dict.fromkeys(live.blocks) if label not in render.blocks]
    dropped_comments = len(set(live.comments) - set(render.comments))

    if live_text is None:
        state = "new"
    elif live_text == render_text:
        state = "unchanged"
    elif removed or removed_blocks:
        state = "removes"
    else:
        state = "additive"

    diff = list(
        difflib.unified_diff(
            (live_text or "").splitlines(),
            render_text.splitlines(),
            fromfile=f"live {live_path}" if live_text is not None else "live (no such file)",
            tofile=f"render {staged_path}",
            lineterm="",
            n=2,
        )
    )
    return VmPlan(
        vmid=vmid,
        live_path=live_path,
        staged_path=staged_path,
        state=state,
        added=added,
        removed=removed,
        removed_blocks=removed_blocks,
        dropped_comments=dropped_comments,
        diff=diff,
        render_text=render_text,
        live_text=live_text,
    )


def _headline(plan: VmPlan) -> str:
    where = f"VM {plan.vmid} ({plan.live_path})"
    if plan.state == "unchanged":
        return f"{where}: unchanged"
    if plan.state == "new":
        return f"{where}: NEW file, {len(plan.added)} line(s) added"
    if plan.state == "additive":
        extra = (
            f", {plan.dropped_comments} comment line(s) not in the render are dropped" if plan.dropped_comments else ""
        )
        return f"{where}: additive, {len(plan.added)} line(s) added{extra}"
    parts = [f"{len(plan.removed)} live rule/option line(s)"] if plan.removed else []
    if plan.removed_blocks:
        parts.append(f"{len(plan.removed_blocks)} managed block(s)")
    return f"{where}: REMOVES {' and '.join(parts)} the render does not carry ({len(plan.added)} line(s) added)"


def render_report(plans: list[VmPlan], allow_rule_removal: bool) -> list[str]:
    report: list[str] = []
    for plan in plans:
        report.append(_headline(plan))
        for line in plan.removed:
            where = f" (in managed block {line.block})" if line.block else ""
            report.append(f"  !! REMOVED [{line.section or 'no section'}] {line.text}{where}")
        for label in plan.removed_blocks:
            report.append(f"  !! REMOVED managed block '# BEGIN {label}' ... '# END {label}'")
        if plan.changed:
            report.extend(f"    {line}" for line in plan.diff)
    removing = [plan for plan in plans if plan.removes]
    if removing:
        names = ", ".join(str(plan.vmid) for plan in removing)
        if allow_rule_removal:
            report.append(
                f"REMOVAL ALLOWED for VM {names} because {ALLOW_VARIABLE}=true; the live files are backed up first."
            )
        else:
            report.append(
                f"REFUSED: the render would remove live rules or managed blocks from VM {names}. Nothing was written."
                f" The render is not the source of truth for those lines. If they must go, pass -e {ALLOW_VARIABLE}=true"
                " (the play backs the files up first); otherwise add the lines to the inventory render or leave the VM out."
            )
    return report


def make_backup(plans: list[VmPlan], backup_root: Path, timestamp: str) -> tuple[Path, str]:
    """Copy every live file that will be replaced; write restore.sh. Returns (directory, restore command)."""
    backup_dir = backup_root / f"fw-backup-{timestamp}"
    suffix = 0
    while True:
        try:
            backup_dir.mkdir(parents=True, exist_ok=False)
            break
        except FileExistsError:
            suffix += 1
            backup_dir = backup_root / f"fw-backup-{timestamp}-{suffix}"
    restore = ["#!/bin/sh", f"# Restores the per-VM Proxmox firewall files replaced at {timestamp}.", "set -eu"]
    for plan in plans:
        if plan.live_text is not None:
            copy = backup_dir / plan.live_path.name
            shutil.copy2(plan.live_path, copy)
            restore.append(f"cp -p {shlex.quote(str(copy))} {shlex.quote(str(plan.live_path))}")
        else:
            restore.append(f"rm -f {shlex.quote(str(plan.live_path))}  # VM {plan.vmid} had no file before")
    restore.append("pve-firewall restart")
    script = backup_dir / "restore.sh"
    script.write_text("\n".join(restore) + "\n", encoding="utf-8")
    script.chmod(0o700)
    return backup_dir, f"sh {shlex.quote(str(script))}"


def install(plans: list[VmPlan]) -> None:
    """Write each render over its live file and read it back; on any failure put the already written files back."""
    written: list[VmPlan] = []
    try:
        for plan in plans:
            shutil.copyfile(plan.staged_path, plan.live_path)
            written.append(plan)
            if plan.live_path.read_text(encoding="utf-8") != plan.render_text:
                raise OSError(f"{plan.live_path} does not hold the render after the write")
    except Exception:
        for plan in written:
            if plan.live_text is None:
                plan.live_path.unlink(missing_ok=True)
            else:
                plan.live_path.write_text(plan.live_text, encoding="utf-8")
        raise


def run(args: argparse.Namespace) -> tuple[int, dict]:
    plans = [plan_vm(vmid, args.live_dir, args.stage_dir) for vmid in sorted(set(args.vmids))]
    refusing = [plan for plan in plans if plan.removes]
    refused = bool(refusing) and not args.allow_rule_removal
    changing = [plan for plan in plans if plan.changed]
    result: dict = {
        "mode": args.mode,
        "refused": refused,
        "allow_rule_removal": args.allow_rule_removal,
        "removal_vmids": [plan.vmid for plan in refusing],
        "changed_vmids": [plan.vmid for plan in changing],
        "installed_vmids": [],
        "backup_dir": None,
        "restore_command": None,
        "report": render_report(plans, args.allow_rule_removal),
        "install_report": [],
        "vms": [
            {
                "vmid": plan.vmid,
                "state": plan.state,
                "added": [line.text for line in plan.added],
                "removed": [{"section": line.section, "line": line.text, "block": line.block} for line in plan.removed],
                "removed_blocks": plan.removed_blocks,
                "dropped_comments": plan.dropped_comments,
            }
            for plan in plans
        ],
    }
    if refused:
        return EXIT_REFUSED, result
    if args.mode == "apply" and changing:
        backup_dir, restore_command = make_backup(changing, args.backup_root, args.timestamp)
        result["backup_dir"] = str(backup_dir)
        result["restore_command"] = restore_command
        install(changing)
        result["installed_vmids"] = [plan.vmid for plan in changing]
        result["install_report"] = [
            f"Installed {len(changing)} firewall file(s) ({', '.join(str(plan.vmid) for plan in changing)});"
            f" copies of the files they replaced are in {backup_dir}",
            f"Restore them with: {restore_command}",
        ]
    return EXIT_OK, result


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("mode", choices=("plan", "apply"))
    parser.add_argument("vmids", nargs="+", type=int, help="VM ids whose staged render is compared with the live file")
    parser.add_argument("--live-dir", type=Path, default=Path("/etc/pve/firewall"))
    parser.add_argument("--stage-dir", type=Path, default=Path("/root"), help="directory holding .lv3-vm-<vmid>.fw")
    parser.add_argument("--backup-root", type=Path, default=Path("/root"))
    parser.add_argument("--allow-rule-removal", action="store_true", help=f"the operator's {ALLOW_VARIABLE}=true")
    parser.add_argument("--timestamp", default=time.strftime("%Y%m%dT%H%M%SZ", time.gmtime()))
    parser.add_argument("--format", choices=("text", "json"), default="text")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        code, result = run(args)
    except (OSError, ValueError) as error:
        print(f"pve_fw_guard: {error}", file=sys.stderr)
        return EXIT_ERROR
    if args.format == "json":
        print(json.dumps(result, ensure_ascii=False))
    else:
        print("\n".join(result["report"] + result["install_report"]))
    return code


if __name__ == "__main__":
    sys.exit(main())
